"""Turn a stored article body into what the article page draws.

Runs after the sanitizer, on markup the sanitizer has already reduced to the
allowlist, so everything added here (heading ids, the summary wrapper, the
table scroller) is generated by us and never taken from the stored text.
"""

from __future__ import annotations

import html as html_lib
import math
import re
from dataclasses import dataclass, field

from django.template.defaultfilters import linebreaks
from django.utils.html import strip_tags
from django.utils.safestring import SafeString, mark_safe
from django.utils.text import slugify
from unidecode import unidecode

from blog.services.html_sanitize import looks_like_html, sanitize_article_html
from blog.services.product_cards import expand_product_blocks

#: Reading speed for Ukrainian prose. Lower than the English 230–250 wpm
#: rule of thumb: longer words, and these articles get read with numbers.
WORDS_PER_MINUTE = 180

_H2_RE = re.compile(r"<h2>(.*?)</h2>", re.S)
_SUMMARY_RE = re.compile(r"^\s*(<p>\s*<strong>\s*Коротко\s*:?\s*</strong>.*?</p>)", re.S | re.I)
_TABLE_RE = re.compile(r"<table>.*?</table>", re.S)


@dataclass
class RenderedArticle:
    body: SafeString
    toc: list[dict[str, str]] = field(default_factory=list)
    minutes: int = 1


def reading_minutes(raw: str) -> int:
    words = len(strip_tags(raw or "").split())
    return max(1, math.ceil(words / WORDS_PER_MINUTE))


def _heading_id(text: str, index: int, used: set[str]) -> str:
    base = slugify(unidecode(text))[:60].strip("-") or f"rozdil-{index}"
    candidate, n = base, 2
    while candidate in used:
        candidate = f"{base}-{n}"
        n += 1
    used.add(candidate)
    return candidate


def _add_heading_ids(body: str) -> tuple[str, list[dict[str, str]]]:
    toc: list[dict[str, str]] = []
    used: set[str] = set()

    def repl(match: re.Match) -> str:
        inner = match.group(1)
        text = re.sub(r"\s+", " ", html_lib.unescape(strip_tags(inner))).strip()
        if not text:
            return match.group(0)
        anchor = _heading_id(text, len(toc) + 1, used)
        toc.append({"id": anchor, "text": text})
        return f'<h2 id="{anchor}">{inner}</h2>'

    return _H2_RE.sub(repl, body), toc


def _wrap_summary(body: str) -> str:
    """The generator opens every article with «Коротко:»; give it the summary box."""
    if body.lstrip().startswith('<div class="bl-summary">'):
        return body
    return _SUMMARY_RE.sub(r'<div class="bl-summary">\1</div>', body, count=1)


def _wrap_tables(body: str) -> str:
    """A bare table would push a phone screen sideways; give it a scroller."""
    out: list[str] = []
    last = 0
    for match in _TABLE_RE.finditer(body):
        before = body[last:match.start()]
        out.append(before)
        if re.search(r'<div class="bl-table">\s*$', before):
            out.append(match.group(0))
        else:
            out.append(f'<div class="bl-table">{match.group(0)}</div>')
        last = match.end()
    out.append(body[last:])
    return "".join(out)


def render_article(raw: str | None) -> RenderedArticle:
    text = str(raw or "")
    if not text.strip():
        return RenderedArticle(body=mark_safe(""), toc=[], minutes=1)
    if not looks_like_html(text):
        return RenderedArticle(body=linebreaks(text), toc=[], minutes=reading_minutes(text))

    body = sanitize_article_html(text)
    body = _wrap_summary(body)
    body = _wrap_tables(body)
    body, toc = _add_heading_ids(body)
    # Last: the cards are our own template output, not article text, and
    # must not be counted as reading or scanned for headings.
    minutes = reading_minutes(body)
    body = expand_product_blocks(body)
    return RenderedArticle(body=mark_safe(body), toc=toc, minutes=minutes)
